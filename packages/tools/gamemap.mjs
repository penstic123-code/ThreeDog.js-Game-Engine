// Game map generator: generates GAMEMAP.md for every game folder (gameDirs in paths.mjs: in the monorepo the engine examples and games/*; in a
//   game's own repo the game folder). npm run map runs it automatically.
// Paths written into GAMEMAP are relative to the game folder (main.js, content/npcs.js) or node_modules/threedog/docs/..., so the map reads the
//   same in the monorepo and in a game installed from npm.
// An AI in a fresh window reads this one file to learn "what this game has": installed modules, files, NPCs, dialogues, items, quests, trigger zones,
//   props, timed events, objective markers, key actions, events, saves, style keys.
// The hand-written "design decisions" live in DESIGN.md in the same directory and are read in as is.
//   node packages/tools/gamemap.mjs           generate
//   node packages/tools/gamemap.mjs --check   check it is up to date (used by npm run check)
import { writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, relative, basename, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { findGames, loadGame, levelIsFile, describeCond as dc, describeEffect as de, mergeRules } from './content-check/load.mjs';
import { ENGINE, MODE, cli, within, workspaceOf, docRef, rel } from './paths.mjs';
import { metadata } from 'threedog/metadata';
import { gameCodeFiles } from './lib/text.mjs';
import { MAX_ROWS, read, uniq, cell, cut, noComments, summary, balanced, balancedAll, splitTop, capped, openWorldModules, installedCalls } from './gamemap/text.mjs';
import { contentLine, templateLines, gridLines, readForLines, npcWhere } from './gamemap/extra.mjs';
import { codeSections } from './gamemap/codeScan.mjs';
import { soundContent } from './gamemap/holes.mjs';
import { questLines } from './gamemap/quests.mjs';
import { placementLines, unusedLines } from './gamemap/placements.mjs';
import { kindMapLines } from './content-check/kinds.mjs';

const MAX_LINES = 220, RECIPES = join(ENGINE, 'docs', 'recipes');
const RULES_DOC = docRef('docs/recipes/20-content-actions-save.md'), API_MD = docRef('docs/API.md');

async function buildMap(dir, data) {
  const { c, holes } = soundContent(data);
  const vocab = mergeRules(c.rules), describeCond = x => dc(x, vocab.conditions), describeEffect = x => de(x, vocab.effects);
  const g = f => relative(dir, f).split(sep).join('/');   // paths in the map are relative to the game folder
  const name = basename(dir), cfile = k => `content/${k}.js`;
  const files = gameCodeFiles(dir), gameFiles = files.filter(f => !g(f).startsWith('content/'));
  const code = gameFiles.map(f => noComments(read(f))).join('\n');
  const main = read(join(dir, 'main.js'));
  // Pages: html files under the workspace root that reference this entry (when the game is itself the workspace the entry is /main.js)
  const ws = workspaceOf(dir) ?? dir, entry = '/' + [relative(ws, dir).split(/[\\/]/).join('/'), 'main.js'].filter(Boolean).join('/');
  const pages = readdirSync(ws).filter(f => f.endsWith('.html') && read(join(ws, f)).includes(`"${entry}"`)).map(f => f === 'index.html' ? '/' : '/' + f);
  const md = [];
  const sec = (title, rows, empty = '(none)') => { md.push('', `## ${title}`, ''); md.push(...(rows.length ? rows : [empty])); };
  if (holes.length) sec('Entries the map could not read (threedog check says what to write)', holes.map(h => `- ${h}`));

  md.push(`# Game map: ${name} (generated, do not edit by hand)`, '');
  md.push('> Generated by `npm run map` by scanning this folder; paths are relative to it. '
    + `Pages: ${pages.join(', ') || '(no page references it)'}, entry \`main.js\`.`);
  md.push(`> Content data is in \`content/*.js\` (condition/effect syntax: \`${RULES_DOC}\`), `
    + 'which main.js hands to the engine with `engine.content.load()`; ' +
    `to look up a name: the module pages listed below (\`${API_MD}\` indexes them).`);
  md.push('', contentLine(c));

  // Design decisions (hand-written)
  const design = join(dir, 'DESIGN.md');
  md.push('', '## Design decisions (hand-written, from DESIGN.md)', '');
  if (existsSync(design)) md.push(...read(design).replace(/^# .*\n/, '').trim().split('\n').map(l => l.replace(/^(#+) /, '$1## ')));
  else md.push('None yet, write them in `DESIGN.md` (why it is designed this way, what not to change).');
  const designDir = join(dir, 'docs', 'design');
  if (existsSync(designDir)) {
    const files = readdirSync(designDir).filter(f => f.endsWith('.md')).sort().map(f => `\`docs/design/${f}\``);
    md.push('', `Design files: ${files.join(', ') || '(none)'}`);
  }

  // Engine modules
  const mods = [];
  const ce = balanced(main, 'createEngine(');
  if (ce) mods.push(`- createEngine: ${cut(ce.replace(/\s+/g, ' ').replace(/canvas: [^,]+, /, ''), 110)}`);
  const use = balancedAll(noComments(main), 'engine.use(').flatMap(u => splitTop(u.body));   // one call per system is as usual as one call for all
  for (const arg of use) {
    const m = arg.match(/^(\w+)\(([\s\S]*)\)$/); if (!m) continue;
    const args = m[2].replace(/\s+/g, ' ').trim();
    if (m[1] === 'openWorld') mods.push(`- openWorld preset (${cut(args, 100)}) → ${openWorldModules(args).join(', ')}`);
    else mods.push(`- ${m[1]}${args ? ` (${cut(args, 100)})` : ''}`);
  }
  // The API page of every installed module, by the function that installs it (the module's name, or a name one module is installed under: followCamera for cameraRig)
  const apiPage = new Map();
  for (const [name, m] of Object.entries(metadata.modules)) if (m.page) for (const fn of [name, ...(m.aliases ?? []).map(a => a.call)]) apiPage.set(fn, `${name}.md`);
  const installed = installedCalls(main);
  sec('Engine modules (engine.use)', mods);
  // Docs for the modules this game installs, and nothing else
  const recipes = existsSync(RECIPES) ? readdirSync(RECIPES).filter(f => f.endsWith('.md')).sort().map(f => [f, read(join(RECIPES, f))]) : [];
  sec(`Read for this game (per installed module: recipe · api page; core API: \`${docRef('docs/api/engine.md')}\`)`,
    readForLines(installed.filter(f => f !== 'openWorld'), apiPage, recipes, docRef));
  md.push('', 'Not used yet (check these before writing the system yourself):', '',
    ...(unusedLines(installed, c, code, docRef).join('\n') || '- (all the common systems are in use)').split('\n'));

  // Files
  // The generic description at the top of content/*.js is the same in every game, so it is not repeated: only the file name and line count
  const fileRow = f => {
    const t = read(f), isContent = g(f).startsWith('content/');
    return `| ${g(f)} | ${t.split('\n').length} | ${isContent ? '' : cut(cell(summary(t)), 100)} |`;
  };
  sec('Files', [`content/*.js is content data: how to write it in \`${docRef('docs/recipes/')}\` `
    + '(02-npc, 03-items-pickups, 04-quests, 20-content-actions-save…).', '',
    '| File | Lines | Description |', '|---|---|---|', ...files.map(fileRow)]);

  // NPC
  const pos = p => p.place ? `${p.place}${p.x || p.z ? `(${p.x ?? 0},${p.z ?? 0})` : ''}` : `(${p.x},${p.z})`;
  const npcUse = (id, i) => !i ? '—' : i.op === 'npc.talk' ? `talk ${i.args?.script ?? id} → start` : `op ${i.op}`;
  sec('NPCs (content/npcs.js)', Object.keys(c.npcs || {}).length ? ['| id | Name | Schedule | Interact |', '|---|---|---|---|',
    ...Object.entries(c.npcs).map(([id, n]) =>
      `| ${id} | ${n.name} | ${npcWhere(n, pos)} | ${npcUse(id, n.interact)} |`)] : []);

  // Dialogue
  const dl = Object.entries(c.dialogues || {}).map(([id, d]) => {
    const nodes = Object.entries(d.nodes || {}).map(([nid, n]) => {
      const fx = n.do ? `[${describeEffect(n.do)}]` : '';
      const variants = Array.isArray(n.text) ? ` (${n.text.length} line variants: ${n.text.filter(v => v.if).map(v => describeCond(v.if)).join('; ')}…)` : '';
      const choice = ch => `${ch.next || 'end'}${ch.if ? `(if ${describeCond(ch.if)})` : ''}${ch.do ? `[${describeEffect(ch.do)}]` : ''}`;
      const go = n.choices ? n.choices.map(choice).join(' / ') : (n.next || 'end');
      return `${nid}${variants}${fx}→${go}`;
    });
    return `- **${id}** (${d.speaker || id}): ${nodes.join(' · ')}`;
  });
  sec('Dialogues (content/dialogues.js, node → destination)', capped(dl, cfile('dialogues')));

  // Items
  const items = Object.entries(c.items || {});
  const pk = c.pickups || [];
  const respawns = uniq(pk.map(p => p.respawn > 0 ? `respawn after ${p.respawn} s` : 'no respawn')).join('/');
  const pkCount = Object.entries(pk.reduce((a, p) => ({ ...a, [p.item]: (a[p.item] || 0) + 1 }), {})).map(([k, n]) => `${k}×${n}`).join(', ');
  sec('Items (content/items.js)', items.length ? ['| id | Name | Description | Stack |', '|---|---|---|---|',
    ...items.slice(0, MAX_ROWS).map(([id, it]) => `| ${id} | ${it.icon || ''} ${it.name} | ${cell(it.desc || '')} | ${it.stack ?? 99} |`),
    ...(items.length > MAX_ROWS ? [`| … | ${items.length - MAX_ROWS} more | see ${cfile('items')} | |`] : []),
    '', `Starting inventory: ${Object.entries(c.startItems || {}).map(([k, n]) => `${k}×${n}`).join(', ') || 'empty'}. ` +
      `Pickups: ${pk.length}${pkCount ? `: ${pkCount}` : ''}${pk.length ? ` (${respawns})` : ''}.`] : []);

  sec('Quests (content/quests.js)', questLines(c, describeCond, describeEffect, pos));
  if (c.rules?.kinds) sec('Game content kinds (content/rules.js kinds)', kindMapLines(c, cut));

  // Trigger zones and level markers
  const levelFile = levelIsFile(code);
  const inGlb = tag => levelFile && !c.level?.markers?.['trigger_' + tag];
  const tl = Object.entries(c.triggers || {}).map(([tag, t]) =>
    `- Trigger zone **${tag}**: ${t.fromLevel ? `level marker trigger_${tag}${inGlb(tag) ? ' (in the level .glb, cannot be read statically)' : ''}`
      : pos(t.position)}` +
      `${t.onEnter ?`; on enter: ${describeEffect(t.onEnter)}` : ''}${t.onExit ? `; on exit: ${describeEffect(t.onExit)}` : ''}`);
  const extra = m => JSON.stringify(Object.fromEntries(Object.entries(m).filter(([k]) => k !== 'x' && k !== 'z')));
  const ml = Object.entries(c.level?.markers || {}).map(([n, m]) => `- Marker ${n}: (${m.x}, ${m.z})${Object.keys(m).length > 2 ? ` ${extra(m)}` : ''}`);
  const pl = Object.entries(c.places || {}).map(([n, d]) => `- Place ${n}: ${d}`);
  sec('Trigger zones, level markers, places', capped([...tl, ...ml, ...pl], 'content/'));

  // Words the game adds itself (conditions only: a game's own action is an op)
  const rl = Object.entries(c.rules?.conditions || {}).map(([w, d]) => `- Condition **${w}** (${d.ref ?? 'any'}): ${d.desc ?? ''}`);
  if (rl.length) sec('Conditions the game adds (content/rules.js)', rl);

  // Object templates (content/templates.js), their placements and runtime spawns
  const tpl = templateLines(c, gameFiles, g);
  if (tpl.length) sec('Object templates (content/templates.js; placed with props { template }, spawned with engine.content.spawn)', tpl);
  // Grids declared in code
  const grids = gridLines(gameFiles, g);
  if (grids.length) sec('Grids (engine.grids)', grids);

  // Where the level comes from: authored placements per content file, and what game code creates at startup that a save would duplicate (rule R33)
  sec('Placements (the level is content; counts per content file)', placementLines(c, gameFiles, g));

  codeSections({ c, dir, g, gameFiles, code, ce, sec });

  md.push('');
  if (md.length > MAX_LINES) { md.length = MAX_LINES - 2; md.push('',
    `> ⚠ The map exceeds ${MAX_LINES} lines and the rest was cut off. For details read content/ and main.js directly.`, ''); }
  return md.join('\n');
}

/**
 * The map of one game: { content }, or { error } when something in it still cannot be read. Why never a throw: the map runs before the content check, so a stack here
 * would stand in front of the one message that says what to fix. Field-level faults past gamemap/holes.mjs land here.
 * @param {string} dir game folder @param {any} data what loadGame read
 */
export async function gameMap(dir, data) {
  try { return { content: await buildMap(dir, data) }; }
  catch (e) { return { error: `an entry in content/ is not what the map can read (${e.message}): threedog check says what to write` }; }
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  // -w (or the current folder) narrows the run to the games inside that workspace (the engine's examples, or one game)
  const { dirs, named, opt } = cli(process.argv.slice(2), { workspace: 'targets', flags: ['check'] });
  const check = !!opt.check;
  let stale = 0;
  for (const dir of findGames().filter(g => !named || dirs.some(d => within(g, d)))) {
    const out = join(dir, 'GAMEMAP.md'), { data, errors } = await loadGame(dir);
    // a file that does not load is left out of data: the map would read as a game without it, and pass
    if (errors.length) { console.error(errors.map(e => `✗ ${rel(out)} not written: ${e}`).join('\n')); stale++; continue; }
    const { content, error } = await gameMap(dir, data);
    if (error) { console.error(`✗ ${rel(out)} not written: ${error}`); stale++; continue; }
    if (check) {
      // the engine's examples stay strict. In a game the map is a convenience that goes stale after any code change, and that breaks nothing: say so, do not fail
      const strict = MODE === 'monorepo' && within(dir, join(ENGINE, 'examples'));
      if ((existsSync(out) ? read(out) : '') !== content) { console.log(`${strict ? '✗' : '⚠'} ${rel(out)} is not up to date, run npm run map`); if (strict) stale++; }
      else console.log(`✓ ${rel(out)} is up to date`);
    } else { writeFileSync(out, content); console.log(`Generated ${rel(out)} (${content.split('\n').length} lines)`); }
  }
  process.exit(stale ? 1 : 0);
}
