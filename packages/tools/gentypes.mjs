// Declaration generator: generates .d.ts from the JSDoc in JS source (TypeScript's official allowJs + declaration + emitDeclarationOnly).
//
//   node packages/tools/gentypes.mjs            generate (step one of npm run map)
//   node packages/tools/gentypes.mjs --check    check the output is up to date (used by npm run check / npm run types, writes no files)
//
// Which source files are migrated: MIGRATED_JS_REL in packages/tools/paths.mjs. Output goes to packages/engine/types/generated/, mirroring the engine source directory layout
// (ui/UI.js → types/generated/ui/UI.d.ts). A migrated file has no hand-written declaration any more: the hand-written index.d.ts / types/*.d.ts only re-export or import them.
//
// Conventions in the source:
//   - Public functions, classes and constants get JSDoc (description + @param / @returns / @type).
//   - To reference a hand-written type: /** @import { Engine } from '../types/core' */ at the top of the file (path relative to the source file; it is rewritten here relative to the generated file).
//   - Things a file exports that are not public API (only used by other engine files) get @internal; generation strips them (stripInternal), so they do not leak into the docs.
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import ts from 'typescript';
import * as P from './paths.mjs';
import { walk } from './lib/text.mjs';

const CHECK = !!P.cli(process.argv.slice(2), { workspace: false, flags: ['check'] }).opt.check;
const ENGINE = P.ENGINE, GEN = P.abs(P.TYPES_GEN_REL);
const sources = P.MIGRATED_JS_REL.map(P.abs);
const posix = p => p.split(sep).join('/');

const options = {
  allowJs: true, checkJs: false, declaration: true, emitDeclarationOnly: true,
  target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler,
  lib: ['lib.es2022.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'], types: [], skipLibCheck: true, noEmitOnError: false,
  outDir: GEN, rootDir: ENGINE, resolveJsonModule: true,
};
// Treat the previous output as "nonexistent": the hand-written core.d.ts imports it, and if TypeScript took it as an input file it would no longer emit to the same path (this also avoids generating new results from old ones)
const host = ts.createCompilerHost(options);
const inGen = f => resolve(f).startsWith(GEN + sep);
const { fileExists, directoryExists } = host;
host.fileExists = f => !inGen(f) && fileExists.call(host, f);
host.directoryExists = d => !inGen(d) && directoryExists.call(host, d);
const program = ts.createProgram(sources, options, host);

// Errors during declaration generation (such as bad JSDoc, an exported type referencing an unexported name): only migrated files are looked at
const problems = [];
for (const f of sources) {
  const sf = program.getSourceFile(f);
  if (!sf) { problems.push(`${P.rel(f)}: not in the TypeScript program`); continue; }
  for (const d of [...program.getSyntacticDiagnostics(sf), ...program.getDeclarationDiagnostics(sf)]) {
    const { line } = sf.getLineAndCharacterOfPosition(d.start ?? 0);
    problems.push(`${P.rel(f)}:${line + 1}  ${ts.flattenDiagnosticMessageText(d.messageText, '\n')} (TS${d.code})`);
  }
}

// Output: keep only the .d.ts of migrated files
const out = new Map();   // absolute path → content
const migrated = new Set(sources.map(f => resolve(f)));
const stripExt = p => p.replace(/\.(d\.ts|js|mjs|ts)$/, '');
program.emit(undefined, (fileName, text) => {
  if (!fileName.endsWith('.d.ts')) return;
  const srcRel = relative(GEN, fileName).replace(/\.d\.ts$/, '.js');
  const src = resolve(ENGINE, srcRel);
  if (!migrated.has(src)) return;
  out.set(resolve(fileName), finish(text, src, fileName));
}, undefined, true);

/** Relative imports must be rewritten: tsc copies the source spelling, but the generated file is in another directory; imports of other migrated files need no change (mirrored layout, same relative position) */
function finish(text, src, outFile) {
  const fix = spec => {
    if (!spec.startsWith('.')) return spec;
    const target = resolve(dirname(src), spec);
    if ([...migrated].some(m => stripExt(m) === stripExt(target))) return spec;
    let r = posix(relative(dirname(outFile), stripExt(target)));
    if (!r.startsWith('.')) r = './' + r;
    return r;
  };
  text = stripInternal(text);
  text = text.replace(/(\bfrom\s+|\bimport\s*\(\s*)(["'])(\.{1,2}\/[^"']*)\2/g, (m, a, q, spec) => `${a}${q}${fix(spec)}${q}`);
  const header = `// Generated by npm run map, do not edit by hand. Source: ${P.rel(src)} (edit the JSDoc in the source, then run npm run map)\n`;
  return header + text.replace(/\r\n/g, '\n');
}

/**
 * Delete declarations tagged @internal in JSDoc (top-level declarations and class members) and class members named _x (private by
 * convention, e.g. input._keyDown), then delete the imports nobody uses any more.
 * tsc's own stripInternal does not apply to JSDoc in JS source (it only understands comments in TS source), so we do it ourselves.
 */
function stripInternal(text) {
  const sf = ts.createSourceFile('x.d.ts', text, ts.ScriptTarget.Latest, true);
  const isInternal = n => (n.jsDoc || []).some(d => (d.tags || []).some(t => t.tagName.text === 'internal'));
  const isPrivate = m => !!m.name && /^_/.test(m.name.getText());
  const cuts = [];
  for (const st of sf.statements) {
    if (isInternal(st)) cuts.push([st.getFullStart(), st.getEnd()]);
    else if (ts.isClassDeclaration(st)) for (const m of st.members) if (isInternal(m) || isPrivate(m)) cuts.push([m.getFullStart(), m.getEnd()]);
  }
  for (const [a, b] of cuts.sort((x, y) => y[0] - x[0])) text = text.slice(0, a) + text.slice(b);
  // Delete unused imports too (look only at the body outside the imports)
  const sf2 = ts.createSourceFile('x.d.ts', text, ts.ScriptTarget.Latest, true);
  const imports = sf2.statements.filter(ts.isImportDeclaration);
  const body = [...imports].reverse().reduce((t, i) => t.slice(0, i.getFullStart()) + t.slice(i.getEnd()), text);
  for (const i of [...imports].reverse()) {
    const c = i.importClause;
    const names = [c?.name?.text, ...(c?.namedBindings && ts.isNamedImports(c.namedBindings) ? c.namedBindings.elements.map(e => e.name.text) : [])].filter(Boolean);
    if (names.length && !names.some(n => new RegExp('\\b' + n + '\\b').test(body))) text = text.slice(0, i.getFullStart()) + text.slice(i.getEnd());
  }
  return text.replace(/\n{3,}/g, '\n\n');
}

// Compare / write
const files = [...out.keys()].sort();
const existing = walk(GEN, { exts: /./, unscoped: true }).map(p => resolve(p));

if (problems.length) { console.log(problems.map(s => '  ✗ ' + s).join('\n')); console.log(`\n✗ ${problems.length} problems while generating declarations`); process.exit(1); }
if (!files.length) { console.log('✗ no declarations generated (is MIGRATED_JS_REL empty?)'); process.exit(1); }

if (CHECK) {
  const stale = files.filter(f => !existsSync(f) || readFileSync(f, 'utf8') !== out.get(f)).map(f => P.rel(f));
  const extra = existing.filter(f => !out.has(f)).map(f => P.rel(f));
  if (stale.length || extra.length) { console.log(`✗ generated declarations are not up to date (${[...stale, ...extra].join(', ')}), run npm run map`); process.exit(1); }
  console.log(`✓ generated declarations are up to date (${P.TYPES_GEN_REL}/ ${files.length} files)`);
} else {
  for (const f of existing) if (!out.has(f)) rmSync(f);
  for (const f of files) { mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, out.get(f)); }
  console.log(`Generated ${P.TYPES_GEN_REL}/ (${files.length} files, from the JSDoc of ${sources.length} JS source files)`);
}
