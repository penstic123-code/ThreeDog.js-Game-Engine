// Terrain edits and custom generators (terrain-edit test page). "Do not bypass" guards: an edit reaches the mesh, engine.surface / groundType,
// collision and vegetation together; it survives save / load and chunk unload / reload; workers build the same edited chunk as the main thread;
// a custom height function that reads an outside variable fails at terrain(), not later in a worker.

// page helpers (installed once per page by setup)
const setup = () => {
  const { createEngine, terrain, vegetation, collision, THREE } = threedogTerrain;
  const wait = () => new Promise(r => setTimeout(r, 5));
  const H = window.TE = {
    async make(threads, opts = {}, key = 'te') {
      const E = createEngine({ canvas: document.createElement('canvas'), headless: true, ui: { loading: false }, threads, urlState: false, saveKey: key + threads });
      E.use(terrain({ seed: 7, viewChunks: 2, ...opts }), vegetation(), collision());
      E.vegetation.define('tree', { geometry: new THREE.ConeGeometry(1, 3, 5), rule: { perChunk: 1500, collider: 0.4, minHeight: -99, maxHeight: 999, maxSlope: 99 } });
      E.ops.define('test.edit', { args: { x: 'number', z: 'number', o: 'any' }, run: (e, a) => e.terrain.edit({ x: a.x, z: a.z }, a.o) });
      await E.start();
      await H.settle(E, { x: 0, z: 0 });
      return E;
    },
    async settle(E, pos) {
      E.focus.set(pos.x, 0, pos.z);
      for (let i = 0; i < 600 && !E.terrain.readyAt(pos); i++) { E.step(1 / 60); await wait(); }
      E.step(0.2);
    },
    // walk far enough that the chunk unloads, then come back (regenerated by a worker when threads are on)
    async away(E, pos) {
      await H.settle(E, { x: 4000, z: 4000 });
      const gone = !E.terrain.chunks.has('0,0');
      await H.settle(E, pos);
      return gone;
    },
    vtx(E, x, z) {
      const CH = E.terrain.chunkSize, cx = Math.floor(x / CH), cz = Math.floor(z / CH), c = E.terrain.chunks.get(cx + ',' + cz);
      if (c?.state !== 'ready') return null;
      const p = c.data.pos, lx = x - cx * CH, lz = z - cz * CH;
      for (let i = 0; i < p.length; i += 3) if (Math.abs(p[i] - lx) < 1e-4 && Math.abs(p[i + 2] - lz) < 1e-4) return p[i + 1];
      return null;
    },
    trees(E, x, z, r) {
      let n = 0;
      for (const c of E.terrain.chunks.values()) {
        const im = E.vegetationDraw.mesh(c, 'tree'); if (!im) continue;
        const a = im.instanceMatrix.array, CH = E.terrain.chunkSize;
        for (let i = 0; i < im.count; i++) {
          if (a[i * 16] === 0 && a[i * 16 + 2] === 0) continue;   // hidden (scaled to 0)
          const dx = c.cx * CH + a[i * 16 + 12] - x, dz = c.cz * CH + a[i * 16 + 14] - z;
          if (dx * dx + dz * dz < r * r) n++;
        }
      }
      let k = 0; E.ground.forEachCollider(x, z, r, () => k++);
      return { n, k };
    },
    chunkSnap(E, key) {
      const c = E.terrain.chunks.get(key), g = E.terrainDraw.meshes.get(c).mesh.geometry.attributes;
      return JSON.stringify([Array.from(g.position.array), Array.from(g.color.array), Array.from(E.vegetationDraw.mesh(c, 'tree')?.instanceMatrix.array ?? [])]);
    },
  };
};

