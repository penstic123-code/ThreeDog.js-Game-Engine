// Event bus: modules do not call each other directly; they "shout" and whoever cares listens.
// const h = engine.events.on('item:add', ({ id, count }) => ...);   // returns a handle; h.remove() cancels (like every add/on in the engine)
// engine.events.emit('item:add', { id: 'fish', count: 1 });
// Event name format: 'noun:action' -- the noun is the singular of the emitter (item, quest, entity... camelCase), the action is a lowercase verb or state (add, done, change...).
//
// Event history: the last historySize entries (default 200) record { tick, name, data }; data keeps only simple values (numbers, strings, booleans; objects become '...') and never holds scene objects.
//   engine.events.recent('item:add') reads recent events of one kind -- for "why did it not fire", first check whether it happened at all.
//
// All events, who emits and who listens: see packages/engine/docs/CODEMAP.md (generated by npm run map)
// In dev (npm run dev) event names are checked: a name never seen before that is one or two letters off a known event warns "did you mean xxx".
/** @import { Handle } from '../types/common' */
/** @import { EventName, EventArgs } from '../types/core' */
import { checkEventName } from './validate.js';

// Event names the engine and modules emit (for spelling checks): generated from EventMap in packages/engine/types/core.d.ts, never a hand-written second copy
import { ENGINE_EVENTS } from './events.generated.js';

/** engine.events: the event bus; modules "shout" and whoever cares listens */
export class Events {
  /** @internal */
  constructor({ check = false, onError = null, now = () => 0 } = {}) {
    /** @internal */ this.map = new Map();
    /** @internal */ this.seen = check ? new Set(ENGINE_EVENTS) : null;
    /** @internal */ this.onError = onError;
    /** @internal */ this.now = now;
    /** @internal history ring: entries in arrival order until full, then _head marks the oldest */ this.history = [];
    /** @internal */ this._head = 0;
    /** How many history entries to keep, default 200; 0 records nothing */
    this.historySize = 200;
  }
  /**
   * Recent events (old -> new); with name, only that kind: { tick = which fixed step, name, data = summary (simple values only; objects become '…') }. For "why did it not fire", first check whether it happened at all
   * @param {string} [name]
   * @returns {{ tick: number, name: string, data: any }[]}
   * @example engine.events.recent('item:add');
  */
  recent(name) {
    const r = this.history, all = this._head ? r.slice(this._head).concat(r.slice(0, this._head)) : r.slice();
    return name ? all.filter(h => h.name === name) : all;
  }
  /** @internal Record one history entry in the ring (O(1); the size may change at runtime) */
  _record(name, data) {
    const n = this.historySize;
    if (this.history.length > n || (this._head && this.history.length < n)) { this.history = this.recent().slice(-n); this._head = 0; }   // historySize changed: re-lay in order
    const e = { tick: this.now(), name, data };
    if (this.history.length < n) this.history.push(e); else { this.history[this._head] = e; this._head = (this._head + 1) % n; }
  }
  /** @internal */
  _check(name) { if (this.seen.has(name)) return; checkEventName(name, this.seen); this.seen.add(name); }
  /**
   * Listen to an event; returns a handle { remove() }
   * @template {EventName} K
   * @param {K} name
   * @param {(...args: EventArgs<K & string>) => void} fn
   * @returns {Handle}
   * @example const h = engine.events.on('item:add', ({ id, count }) => console.log(id, count));
   * h.remove();
  */
  on(name, fn) { this.seen && this._check(name); if (!this.map.has(name)) this.map.set(name, new Set()); this.map.get(name).add(fn); return { remove: () => this._off(name, fn) }; }
  /**
   * Listen once; returns a handle { remove() } (can be removed before it fires)
   * @template {EventName} K
   * @param {K} name
   * @param {(...args: EventArgs<K & string>) => void} fn
   * @returns {Handle}
  */
  once(name, fn) { const h = this.on(name, (...a) => { h.remove(); fn(...a); }); return h; }
  /** @internal Total listeners (used by engine.counts()) */
  get size() { let n = 0; for (const s of this.map.values()) n += s.size; return n; }
  /** @internal Remove all listeners (engine.dispose calls it) */
  dispose() { this.map.clear(); }
  /** @internal */
  _off(name, fn) { this.map.get(name)?.delete(fn); }   // listeners are removed only through the handle, h.remove()
  /**
   * Emit an event
   * @template {EventName} K
   * @param {K} name
   * @param {EventArgs<K & string>} args
   * @example engine.events.emit('item:add', { id: 'fish', count: 1 });
  */
  emit(name, ...args) {
    this.seen && this._check(name);
    if (this.historySize > 0) this._record(name, brief(args[0]));   // 0 = no history: no allocation, no copying
    const s = this.map.get(name); if (s) for (const fn of [...s]) { try { fn(...args); } catch (err) { if (this.onError) this.onError(name, err); else console.error(`[event ${name}]`, err); } } }
}

/** Summary of event data: keeps simple values only; objects and arrays become '…' (history must not hold scene objects) */
function brief(v) {
  if (v == null || typeof v !== 'object') return typeof v === 'function' ? '…' : v;
  if (Array.isArray(v) || v.isObject3D) return '…';
  const out = {};
  let n = 0;
  for (const k in v) { if (n++ >= 8) break; const x = v[k]; out[k] = x == null || (typeof x !== 'object' && typeof x !== 'function') ? x : '…'; }
  return out;
}
